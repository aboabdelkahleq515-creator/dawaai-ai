"""
Database connection and schema initialization for Dawaa'i AI.
Uses SQLite with Write-Ahead Logging (WAL) mode for concurrency and durability.
"""
import sqlite3
import json
import re
from datetime import datetime, timezone
from contextlib import contextmanager
from app.config import settings

def normalize_arabic(text: str) -> str:
    """Normalizes Arabic text removing tashkeel, alef variants, and standardizing characters."""
    if not text:
        return ""
    # Strip diacritics / tashkeel
    text = re.sub(r'[\u064B-\u065F\u0670]', '', str(text))
    # Normalize alef variants
    for a in ['أ', 'إ', 'آ', 'ٱ']:
        text = text.replace(a, 'ا')
    # Normalize taa marbuta and alif maqsura
    text = text.replace('ة', 'ه').replace('ى', 'ي')
    # Strip tatweel / kashida
    text = text.replace('ـ', '')
    return text.lower().strip()

def get_connection():
    conn = sqlite3.connect(settings.DATABASE_PATH, timeout=30.0)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA journal_mode=WAL;")
    conn.execute("PRAGMA foreign_keys=ON;")
    # Register Arabic normalization function for robust search
    conn.create_function("NORM_AR", 1, normalize_arabic)
    return conn

@contextmanager
def get_db():
    conn = get_connection()
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()

def init_db():
    """Initializes tables and indexes with production-ready constraints."""
    with get_db() as conn:
        cursor = conn.cursor()
        
        # 1. Users Table
        cursor.execute("""
        CREATE TABLE IF NOT EXISTS users (
            id TEXT PRIMARY KEY,
            google_id TEXT UNIQUE,
            email TEXT UNIQUE NOT NULL,
            full_name TEXT NOT NULL,
            picture_url TEXT,
            preferred_language TEXT DEFAULT 'ar',
            role TEXT DEFAULT 'user',
            has_completed_onboarding INTEGER DEFAULT 0,
            created_at TEXT NOT NULL,
            updated_at TEXT NOT NULL
        );
        """)
        
        # 2. Medicines Catalog Table (Verified records)
        cursor.execute("""
        CREATE TABLE IF NOT EXISTS medicines (
            id TEXT PRIMARY KEY,
            slug TEXT UNIQUE NOT NULL,
            trade_name_en TEXT NOT NULL,
            trade_name_ar TEXT NOT NULL,
            generic_name TEXT NOT NULL,
            active_ingredient_en TEXT NOT NULL,
            active_ingredient_ar TEXT NOT NULL,
            category_en TEXT NOT NULL,
            category_ar TEXT NOT NULL,
            dosage_form_en TEXT NOT NULL,
            dosage_form_ar TEXT NOT NULL,
            strength TEXT NOT NULL,
            indications_en TEXT NOT NULL,
            indications_ar TEXT NOT NULL,
            dosage_instructions_en TEXT NOT NULL,
            dosage_instructions_ar TEXT NOT NULL,
            contraindications_en TEXT NOT NULL,
            contraindications_ar TEXT NOT NULL,
            side_effects_en TEXT NOT NULL,
            side_effects_ar TEXT NOT NULL,
            interactions_en TEXT NOT NULL,
            interactions_ar TEXT NOT NULL,
            pregnancy_safety_en TEXT NOT NULL,
            pregnancy_safety_ar TEXT NOT NULL,
            pediatric_safety_en TEXT,
            pediatric_safety_ar TEXT,
            geriatric_safety_en TEXT,
            geriatric_safety_ar TEXT,
            storage_en TEXT NOT NULL,
            storage_ar TEXT NOT NULL,
            source_authority TEXT NOT NULL,
            source_url TEXT NOT NULL,
            is_verified INTEGER DEFAULT 1,
            verified_at TEXT NOT NULL,
            created_at TEXT NOT NULL
        );
        """)

        # Auto-migrate existing database for pediatric and geriatric columns
        cursor.execute("PRAGMA table_info(medicines);")
        columns = [col[1] for col in cursor.fetchall()]
        for col_name in ["pediatric_safety_en", "pediatric_safety_ar", "geriatric_safety_en", "geriatric_safety_ar"]:
            if col_name not in columns:
                cursor.execute(f"ALTER TABLE medicines ADD COLUMN {col_name} TEXT;")

        # Data-origin tracking: separates curated/pharmacist-reviewed records from AI-generated ones
        if "data_origin" not in columns:
            cursor.execute("ALTER TABLE medicines ADD COLUMN data_origin TEXT DEFAULT 'curated';")
        if "reviewed_by" not in columns:
            cursor.execute("ALTER TABLE medicines ADD COLUMN reviewed_by TEXT;")
        if "price" not in columns:
            cursor.execute("ALTER TABLE medicines ADD COLUMN price REAL;")
        if "manufacturer" not in columns:
            cursor.execute("ALTER TABLE medicines ADD COLUMN manufacturer TEXT;")

        # CLEAN-UP: records auto-saved by the old scanner (id 'med-ai-*') were generated by an LLM and
        # were wrongly flagged as verified. Check before running full scan to keep startup instant.
        cursor.execute("SELECT 1 FROM medicines WHERE id LIKE 'med-ai-%' AND (data_origin IS NULL OR data_origin != 'ai_unverified' OR is_verified = 1) LIMIT 1;")
        if cursor.fetchone():
            cursor.execute("""
                UPDATE medicines
                SET is_verified = 0, data_origin = 'ai_unverified'
                WHERE id LIKE 'med-ai-%' AND (data_origin IS NULL OR data_origin != 'ai_unverified' OR is_verified = 1);
            """)

        # Queue of AI-recognized medicines waiting for pharmacist review (replaces auto-insert as verified)
        cursor.execute("""
        CREATE TABLE IF NOT EXISTS pending_medicines (
            id TEXT PRIMARY KEY,
            detected_text TEXT NOT NULL,
            extracted_json TEXT,
            ai_report_json TEXT,
            scan_count INTEGER DEFAULT 1,
            status TEXT DEFAULT 'pending', -- 'pending', 'approved', 'rejected'
            created_at TEXT NOT NULL,
            last_seen_at TEXT NOT NULL
        );
        """)
        cursor.execute("CREATE INDEX IF NOT EXISTS idx_pending_status ON pending_medicines(status);")
        
        # 3. User Activities Table (Records genuine meaningful use)
        cursor.execute("""
        CREATE TABLE IF NOT EXISTS user_activities (
            id TEXT PRIMARY KEY,
            user_id TEXT NOT NULL,
            event_type TEXT NOT NULL, -- 'medicine_view', 'leaflet_processed', 'assistant_explanation', 'medicine_scanned'
            target_id TEXT,
            target_name TEXT,
            is_successful INTEGER DEFAULT 1,
            metadata_json TEXT,
            created_at TEXT NOT NULL,
            FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
        );
        """)
        
        # 4. Reviews Table (Mandatory first-use review and public testimonials)
        cursor.execute("""
        CREATE TABLE IF NOT EXISTS reviews (
            id TEXT PRIMARY KEY,
            user_id TEXT NOT NULL,
            rating INTEGER NOT NULL CHECK (rating >= 1 AND rating <= 5),
            comment TEXT,
            category TEXT, -- 'ease_of_use', 'medicine_search', 'leaflet_reader', 'ai_explanations', 'design', 'other'
            review_type TEXT DEFAULT 'first_use',
            consent_public INTEGER DEFAULT 1,
            is_published INTEGER DEFAULT 1,
            moderation_status TEXT DEFAULT 'approved', -- 'approved', 'pending', 'hidden'
            created_at TEXT NOT NULL,
            updated_at TEXT NOT NULL,
            FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
            UNIQUE(user_id, review_type)
        );
        """)
        
        # 5. Processed Documents Table
        cursor.execute("""
        CREATE TABLE IF NOT EXISTS processed_documents (
            id TEXT PRIMARY KEY,
            user_id TEXT,
            doc_type TEXT NOT NULL, -- 'leaflet', 'medicine_box'
            file_name TEXT NOT NULL,
            extracted_text TEXT,
            structured_data_json TEXT,
            is_successful INTEGER DEFAULT 1,
            created_at TEXT NOT NULL
        );
        """)
        
        # Indexes for fast lookup & aggregation
        cursor.execute("CREATE INDEX IF NOT EXISTS idx_users_google_id ON users(google_id);")
        cursor.execute("CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);")
        cursor.execute("CREATE INDEX IF NOT EXISTS idx_medicines_slug ON medicines(slug);")
        cursor.execute("CREATE INDEX IF NOT EXISTS idx_medicines_names ON medicines(trade_name_en, trade_name_ar);")
        cursor.execute("CREATE INDEX IF NOT EXISTS idx_activities_user_event ON user_activities(user_id, event_type, is_successful);")
        cursor.execute("CREATE INDEX IF NOT EXISTS idx_reviews_user_type ON reviews(user_id, review_type);")
        cursor.execute("CREATE INDEX IF NOT EXISTS idx_reviews_published ON reviews(is_published, moderation_status);")
